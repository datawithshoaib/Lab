# basic algorithm
def selection_sort(arr):
    n = len(arr)
    for i in range(n):
        min_index = i
        for j in range(i + 1, n):
            if arr[j] < arr[min_index]:
                min_index = j
        arr[i], arr[min_index] = arr[min_index], arr[i]
    return arr

# optimized algorithm
def selection_sort_optim(arr):
    n = len(arr)
    for i in range(n-1): # no need to check the last element
        min_index = i
        for j in range(i + 1, n):
            if arr[j] < arr[min_index]:
                min_index = j
        if min_index != i: # only swap if the minimum is not already in place
            arr[i], arr[min_index] = arr[min_index], arr[i]
    return arr

